import { test, expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
const { PrismaClient } = require('../../backend/node_modules/@prisma/client');
const argon2 = require('../../backend/node_modules/argon2');
const db = new PrismaClient();
test.use({ actionTimeout: 15000 });
const suffix = randomUUID();
const email = `block-test-${suffix}@example.invalid`;
const password = `Test-${suffix}`;
let coachId: string;
test.beforeAll(async () => {
  coachId = (await db.user.create({ data: { email, name: 'Coach bloques', role: 'COACH', passwordHash: await argon2.hash(password) } })).id;
  await db.exercise.createMany({ data: [{ coachId, name: 'Squat', muscleGroup: 'Piernas' }, { coachId, name: 'Bench Press', muscleGroup: 'Pecho' }] });
  await db.exerciseModifier.createMany({ data: ['Low Bar', '2ct Pause'].map(name => ({ coachId, name, normalizedName: name.toLowerCase(), category: 'Variantes' })) });
});
test.afterAll(async () => {
  if (coachId) {
    await db.block.deleteMany({ where: { coachId } });
    await db.exercise.deleteMany({ where: { coachId } });
    await db.auditLog.deleteMany({ where: { actorId: coachId } });
    await db.user.delete({ where: { id: coachId } });
  }
  await db.$disconnect();
});
test('API: validaciones, conflictos, aislamiento y restricciones SQL', async ({ request }) => {
  const base = 'http://localhost:3101/api/v1';
  const login = await request.post(`${base}/auth/login`, { data: { email, password } });
  const headers = { Authorization: `Bearer ${(await login.json()).data.accessToken}` };
  expect((await request.post(`${base}/block-library`, { headers, data: { name: '   ', weekCount: 6 } })).status()).toBe(400);
  const result = await request.post(`${base}/block-library`, { headers, data: { name: 'API temporal', weekCount: 1 } });
  expect(result.ok()).toBe(true);
  const block = (await result.json()).data;
  const body = { name: block.name, revision: block.revision, folderId: null, weeks: block.weeks };
  body.weeks[0].days = Array.from({ length: 8 }, (_, i) => ({ id: randomUUID(), name: `Día ${i}`, exercises: [] }));
  expect((await request.patch(`${base}/block-library/${block.id}`, { headers, data: body })).status()).toBe(400);
  body.weeks[0].days.pop();
  expect((await request.patch(`${base}/block-library/${block.id}`, { headers, data: body })).status()).toBe(200);
  expect((await request.patch(`${base}/block-library/${block.id}`, { headers, data: body })).status()).toBe(409);
  await expect(db.session.create({ data: { weekId: body.weeks[0].id, name: 'Octavo', order: 8 } })).rejects.toThrow();
  const other = await db.user.create({ data: { email: `other-${suffix}@example.invalid`, name: 'Otro coach', role: 'COACH', passwordHash: await argon2.hash(password) } });
  try {
    const otherLogin = await request.post(`${base}/auth/login`, { data: { email: other.email, password } });
    const otherHeaders = { Authorization: `Bearer ${(await otherLogin.json()).data.accessToken}` };
    expect((await request.get(`${base}/block-library/${block.id}`, { headers: otherHeaders })).status()).toBe(404);
    expect((await request.delete(`${base}/block-library/${block.id}`, { headers: otherHeaders })).status()).toBe(404);
    expect((await request.get(`${base}/blocks/${block.id}`, { headers })).status()).toBe(404);
    const modifier = { name: '  low BAR  ', category: 'Variantes' };
    const first = await request.post(`${base}/block-library/catalog/modifiers`, { headers, data: modifier });
    const second = await request.post(`${base}/block-library/catalog/modifiers`, { headers, data: { ...modifier, name: 'Low Bar' } });
    expect((await first.json()).data.id).toBe((await second.json()).data.id);
  } finally {
    await db.auditLog.deleteMany({ where: { actorId: other.id } });
    await db.user.delete({ where: { id: other.id } });
    await request.delete(`${base}/block-library/${block.id}`, { headers });
  }
});
